#!/usr/bin/env python3
"""Build the LPC2148 SD package and the bounded firmware route/settings manifest."""
import argparse,base64,hashlib,json,re,zipfile,io
from pathlib import Path
from html.parser import HTMLParser
from generate_assets import build_html,WEB
from layout_pages import normalize_layout
HERE=Path(__file__).resolve().parent

class InlineResources(HTMLParser):
 def handle_starttag(self,tag,attrs):
  attrs=dict(attrs)
  for name in ('src','srcset','background','poster','data'):
   value=attrs.get(name,'')
   if value and not value.startswith(('data:','#')):
    raise ValueError('Non-inline resource: '+tag+' '+name+'='+value)
  if tag=='link' and attrs.get('href') and not attrs['href'].startswith('data:'):
   raise ValueError('Non-inline link resource')
  if '@import' in attrs.get('style','').lower():raise ValueError('External CSS import')
 def handle_startendtag(self,tag,attrs):self.handle_starttag(tag,attrs)


def build():
 spec=json.loads((HERE/'pages.json').read_text());fields=spec['fields'];index={f['name']:i for i,f in enumerate(fields)}
 def c(s):return json.dumps(s,ensure_ascii=False)
 lines=['/* Generated by Application/LPC2148/build_pages.py. */','#include "lpc_pages.h"','const LpcField LPC_Fields[] = {']
 for f in fields:
  kind={'text':0,'checkbox':1,'secret':2,'select':3}[f['kind']]
  lines.append('    {%s,%s,%s,%du,%du},'%(c(f['name']),c(f['default']),c('|'.join(f['choices'])),f['maximum'],kind))
 lines.append('};');forms=[];members=[];pagemeta=[]
 for p in spec['pages']:
  start=len(forms)
  for form in p['forms']:
   ids=[index[name] for name in form['fields']];forms.append((len(members),len(ids)));members+=ids
  pagemeta.append((p['title'],p['source'],start,len(p['forms'])))
 lines+=['const uint16_t LPC_Members[] = {',','.join(map(str,members)) or '0','};','const LpcForm LPC_Forms[] = {']
 lines+=['    {%du,%du},'%f for f in forms];lines+=['};','const LpcPage LPC_Pages[] = {']
 lines+=['    {%s,%s,%du,%du},'%(c(t),c(s),a,n) for t,s,a,n in pagemeta];lines+=['};','']
 manifest='\n'.join(lines)
 schema=int(hashlib.sha256(json.dumps([[f['name'],f['kind'],f['maximum']] for f in fields],ensure_ascii=False).encode()).hexdigest()[:8],16)
 header='''/* Generated counts and schema, not runtime settings. */
#ifndef LPC_MANIFEST_H
#define LPC_MANIFEST_H
#define LPC_PAGE_COUNT %du
#define LPC_FIELD_COUNT %du
#define LPC_SCHEMA 0x%08xu
#endif
'''%(len(pagemeta),len(fields),schema)
 # All resources are inline in each SD document, preserving one request per page.
 for page in spec['pages']:
  page['body']=re.sub(r'\sdata-role=[\"\']page[\"\']', '', page['body'])
 root=build_html();head=root[:root.rindex('</head><body>')]
 # Render the body before the large inline libraries arrive over ESP/UART.
 # Extract only actual script elements; escaped </script in JS stays intact.
 scripts=re.findall(r'<script\b[^>]*>.*?</script\s*>',head,re.I|re.S)
 head=re.sub(r'<script\b[^>]*>.*?</script\s*>','',head,flags=re.I|re.S)
 head+='<link rel="icon" href="data:,">'
 head+="<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'self' data:; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; font-src data:; connect-src 'self'; object-src 'none'\">"
 head+='</head><body>'
 common_css='<style>'+ (WEB/'layout.css').read_text()+'</style>'
 adapter=(WEB/'legacy.js').read_text()+'\n'+(WEB/'layout.js').read_text()
 nav='<nav class="lpc-navigation"><a href="/nowa">Panel /nowa</a> | <a href="/lpc">Wszystkie strony LPC2148</a> | <a href="/set">Konfiguracja portów H7</a></nav><div id="lpc-status" class="lpc-status" role="status">Wczytywanie ustawień i danych…</div>'
 # Map legacy navigation to numbered destinations, using source file names.
 mapping={p['source'].lower():p['path'] for p in spec['pages']}
 links={'101':'Strona/temp_sms_c.htm','102':'Strona/Termostat_c.htm','103':'Strona/temp_maski_c.htm','104':'Strona/Rejestrator_c.htm','105':'Strona/Zal_wyl_PK_c.htm','106':'Strona/Autotimer_c.htm','107':'Strona/we_sms_c.htm','108':'Strona/Autoster_c.htm','109':'Strona/we_maski_c.htm','110':'Strona/Zaleznosci_c.htm','111':'Strona/irda_c.htm','112':'Strona/email_c.htm','020':'Strona/Lan_c.htm','200':'Strona/Zal_Wyl_PK_g.htm','500':'Strona/Mobilna/Glowny.htm','516':'Strona/Mobilna/Panel_kontrolny_v1.htm','517':'Strona/Mobilna/Panel_kontrolny_v2.htm','518':'Strona/Mobilna/Panel_kontrolny_v3.htm'}
 rows=[];items=[]
 for p in spec['pages']:
  body=normalize_layout(p['body'],p['number'])
  def css_image(match):
   name=match[1].strip(' \"\'')
   if name.startswith('data:'):return match[0]
   image=next((path for path in WEB.rglob('*') if path.is_file() and path.relative_to(WEB).as_posix().lower()==name.lstrip('/').lower()),None)
   if image is None:raise ValueError('Missing inline CSS image '+name)
   mime={'.jpg':'image/jpeg','.png':'image/png','.gif':'image/gif','.svg':'image/svg+xml'}[image.suffix.lower()]
   return 'url(data:'+mime+';base64,'+base64.b64encode(image.read_bytes()).decode()+')'
  body=re.sub(r'url\(([^)]*)\)',css_image,body,flags=re.I)
  def link(m):
   value=m[1]
   if value.startswith('#'):return m[0]
   num=re.search(r'(?:lpc\.cgi/)?(\d{3})$',value)
   target=mapping.get(links.get(num[1], '').lower()) if num else None
   if not target:
    name=value.split('/')[-1].lower()
    target=next((q['path'] for q in spec['pages'] if q['source'].split('/')[-1].lower()==name),None)
   return 'href="'+(target or '/lpc')+'"'
  body=re.sub(r'href="([^"]*)"',link,body)
  boot='<script>window.LPC_PAGE='+str(p['number'])+';window.LPC_FORM_FIELDS='+json.dumps([[name for name in form['fields']] for form in p['forms']])+ ';window.LPC_FORM_ACTIONS='+json.dumps([form['submit'] for form in p['forms']])+ ';window.LPC_SOURCES='+json.dumps(p['source'])+';</script>'
  html=head+common_css+'<div data-role="page"><div data-role="content">'+nav+'<main id="lpc-content">'+body+'</main></div></div>'+''.join(scripts)+boot+'<script>'+adapter.replace('</script','<\\/script')+'</script></body></html>'
  InlineResources().feed(html)
  items.append((f'LPC/P{p["number"]:05d}.HTM',html.encode()))
  rows.append({'address':p['path'],'source':p['source'],'title':p['title'],'forms':len(p['forms'])})
 readme='Kopiuj folder LPC do katalogu głównego karty SD (FAT/FAT32).\n/nowa pozostaje we Flash; /nowa1.. wymagają tego pakietu.\nLista stron: /lpc lub STRONY.csv.\n'
 items += [('CZYTAJ.txt',readme.encode()),('STRONY.csv',('adres;plik źródłowy;tytuł\n'+'\n'.join(';'.join([r['address'],r['source'],r['title'].replace(';',',')]) for r in rows)).encode('utf-8-sig'))]
 out=io.BytesIO()
 with zipfile.ZipFile(out,'w',zipfile.ZIP_DEFLATED,compresslevel=9) as z:
  for name,data in items:
   entry=zipfile.ZipInfo(name,date_time=(2026,1,1,0,0,0));entry.compress_type=zipfile.ZIP_DEFLATED;z.writestr(entry,data)
 return manifest,header,out.getvalue(),rows

def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 manifest,header,package,rows=build()
 outputs={'lpc_manifest.c':manifest.encode(),'lpc_manifest.h':header.encode(),'sdcard.zip':package,'routes.json':json.dumps(rows,ensure_ascii=False,indent=2).encode()}
 for name,data in outputs.items():
  path=HERE/name
  if args.check:
   if not path.exists() or path.read_bytes()!=data:raise SystemExit('Stale '+str(path))
  else:path.write_bytes(data)
 print(f'PASS: {len(rows)} user pages; SD package {len(package)/1024/1024:.1f} MiB; stable routes and manifest.')
if __name__=='__main__':main()
