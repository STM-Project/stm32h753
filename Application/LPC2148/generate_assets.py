#!/usr/bin/env python3
"""Generate the SD panel route metadata; HTML is packaged by build_pages.py. Run with --check in CI."""
import argparse
import base64
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / 'Application/LPC2148/web'
OUT = ROOT / 'Application/LPC2148/http_lpc_assets.c'
MIME = {'.html':'text/html; charset=UTF-8','.js':'application/javascript; charset=UTF-8',
        '.css':'text/css; charset=UTF-8','.svg':'image/svg+xml','.png':'image/png','.gif':'image/gif'}
def build_html():
    """One HTTP response: inline JS, CSS, SVG and all CSS image resources."""
    html = (WEB / 'index.html').read_text()
    def script(match):
        path = match.group(1).removeprefix('/lpc/')
        code = (WEB / path).read_text()
        if path.endswith('jquery.thermometer.js'):
            code = 'window.HTTP_LPC_SVG=' + json.dumps((WEB/'svg/thermo-bottom.svg').read_text()) + ';\n' + code
        code = re.sub(r'</script', lambda _: r'<\/script', code, flags=re.I)
        return '<script>' + code + '</script>'
    def stylesheet(match):
        path = WEB / match.group(1).removeprefix('/lpc/')
        css = path.read_text()
        def image(match):
            name = match.group(1).strip('\"\'')
            if name.startswith('data:'): return match.group(0)
            image_path = path.parent / name
            encoded = base64.b64encode(image_path.read_bytes()).decode('ascii')
            return 'url(data:' + MIME[image_path.suffix] + ';base64,' + encoded + ')'
        css = re.sub(r'url\(([^)]+)\)', image, css)
        return '<style>' + css + '</style>'
    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', stylesheet, html)
    html = re.sub(r'<script src="([^"]+)"></script>', script, html)
    return html

def generate():
    return '\n'.join([
        '/* Generated by Application/LPC2148/generate_assets.py. */',
        '#include "http_lpc_panel.h"', '#include "lpc_pages.h"', '#include <string.h>',
        'static const HTTP_LpcAsset asset = {"/nowa", "text/html; charset=UTF-8", LPC_PANEL_SD_PAGE};',
        'const HTTP_LpcAsset *HTTP_LpcFindAsset ( const char *path, size_t length )', '{',
        '\treturn path && length == 5u && !memcmp ( path, "/nowa", 5u ) ? &asset : NULL;', '}', ''])
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    text=generate()
    if args.check:
        if not OUT.exists() or OUT.read_text()!=text:raise SystemExit('Stale LPC panel assets')
    else:OUT.write_text(text)
    print('PASS: LPC SD route metadata matches sources.')
if __name__=='__main__':main()
