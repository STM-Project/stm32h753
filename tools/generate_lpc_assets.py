#!/usr/bin/env python3
"""Embed the offline LPC panel resources in STM32 Flash. Run with --check in CI."""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / 'web/lpc2148'
OUT = ROOT / 'Application/HTTP/http_lpc_assets.c'
MIME = {'.html':'text/html; charset=UTF-8','.js':'application/javascript; charset=UTF-8',
        '.css':'text/css; charset=UTF-8','.svg':'image/svg+xml','.png':'image/png','.gif':'image/gif'}
def generate():
    lines = ['/* Generated by tools/generate_lpc_assets.py. */', '#include "http_lpc_panel.h"', '#include <string.h>']
    files = sorted(p for p in WEB.rglob('*') if p.suffix in MIME)
    for i,p in enumerate(files):
        data = p.read_bytes()
        lines.append(f'static const char asset_{i}[] =')
        for start in range(0,len(data),80):
            chunk=data[start:start+80]
            lines.append('"'+''.join('\\x%02x'%c for c in chunk)+'"')
        lines[-1]+=';'
    lines.append('static const HTTP_LpcAsset assets[] = {')
    for i,p in enumerate(files):
        path='/nowa' if p.name=='index.html' else '/lpc/'+p.relative_to(WEB).as_posix()
        lines.append(f'    {{"{path}",asset_{i},"{MIME[p.suffix]}",sizeof(asset_{i})-1u}},')
    lines.extend(['};', '''const HTTP_LpcAsset *HTTP_LpcFindAsset(const char *path,size_t length)
{
    if (!path) return NULL;
    for (size_t i=0;i<sizeof assets/sizeof assets[0];i++)
        if (strlen(assets[i].path)==length && !memcmp(path,assets[i].path,length)) return &assets[i];
    return NULL;
}''',''])
    return '\n'.join(lines)
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    text=generate()
    if args.check:
        if not OUT.exists() or OUT.read_text()!=text:raise SystemExit('Stale LPC panel assets')
    else:OUT.write_text(text)
    print('PASS: offline LPC assets match Flash sources.')
if __name__=='__main__':main()
