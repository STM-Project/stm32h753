#!/usr/bin/env python3
"""Generate the complete typed settings view from the same schema as the forms."""
import argparse
import json
import re
from pathlib import Path

import import_sandwitch_settings as catalog

ROOT = Path(__file__).resolve().parents[1]
GROUPS = [
    ("/lan", "Lan", "lan"), ("/wifi", "Wifi", "wifi"),
    ("/czas", "Clock", "clock"), ("/gsm", "Gsm", "gsm"),
    ("/nrf", "Lora", "lora"), ("/we", "Input", "inputs"),
    ("/eol", "Eol", "eol"), ("/wypk", "Output", "outputs"),
    ("/tim", "Timer", "timers"), ("/term", "Thermostat", "thermostats"),
    ("/etr", "Counter", "counters"), ("/rej", "Recorder", "recorder"),
    ("/maskisms", "Sms", "sms"), ("/maskimail", "Email", "email"),
    ("/nap", "Adc", "adc"), ("/Rot", "Rotation", "rotation"),
    ("/logic", "Logic", "logic"), ("/wykres1", "MeasurementGraph", "measurementGraphs"),
    ("/wykres2", "CounterGraph", "counterGraphs"),
]
CUSTOM = {
    "Output": "char name[31]; char onLabel[21]; char offLabel[21];",
    "Timer": "HTTP_SettingsTime on[4]; HTTP_SettingsTime off[4]; uint8_t weekdays[7]; uint8_t enabled; HTTP_OutputSettings output;",
    "Thermostat": "char sensor[4]; int64_t threshold_x100; int64_t hysteresis_x100; uint32_t delay_seconds; HTTP_OutputSettings output;",
}


def member(field):
    name = re.sub(r"^n_(?:s_)?", "", field["name"])
    name = re.sub(r"_(?:\{\{N\}\}|000)$", "", name)
    name = name.replace("{{I}}", "channel")
    name = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if name[0].isdigit():
        name = "field_" + name
    if field["kind"] == "DECIMAL":
        name += "_x100"
    elif field["kind"] == "DURATION":
        name += "_seconds"
    return name


def value_type(field):
    kind = field["kind"]
    if kind == "CHECKBOX" or (kind == "SELECT" and field["choices"] == "nie|tak"):
        return "uint8_t", "BOOL"
    if kind == "UINT" or (kind == "SELECT" and all(re.fullmatch(r"\d+", x) for x in field["choices"].split("|"))):
        return "uint32_t", "UINT"
    if kind == "DECIMAL": return "int64_t", "DECIMAL"
    if kind == "DURATION": return "uint32_t", "DURATION"
    if kind == "TIME": return "HTTP_SettingsTime", "TIME"
    if kind == "IPV4": return "uint32_t", "IPV4"
    if kind == "MAC": return "uint64_t", "MAC"
    return f'char[{field["max_length"] + 1}]', "TEXT"


def target(type_name, field):
    name = field["name"]
    if name.startswith("n_s_PK_") and type_name in CUSTOM:
        suffix = {"nazwa": "name", "nazwa_on": "onLabel", "nazwa_of": "offLabel"}
        key = name.removeprefix("n_s_PK_").removesuffix("_{{N}}")
        return ("" if type_name == "Output" else "output.") + suffix[key]
    if type_name == "Timer":
        match = re.fullmatch(r"n_s_Tim_godz(ON|OF)([1-4])_\{\{N\}\}", name)
        if match: return f'{"on" if match[1] == "ON" else "off"}[{int(match[2])-1}]'
        match = re.fullmatch(r"n_s_Tim_akt([1-8])_\{\{N\}\}", name)
        assert match, name
        return "enabled" if match[1] == "8" else f"weekdays[{int(match[1])-1}]"
    if type_name == "Thermostat":
        return {"n_s_Term_seltempwilg_{{N}}": "sensor", "n_s_Term_prog_{{N}}": "threshold_x100",
                "n_s_Term_hist_{{N}}": "hysteresis_x100", "n_s_Term_czas_reak_{{N}}": "delay_seconds"}[name]
    return member(field)


def generate(pages):
    by_route = {p["route"]: (i, p) for i, p in enumerate(pages)}
    h = ['/* Generated by tools/generate_settings_struct.py. */',
         '#ifndef HTTP_ALL_SETTINGS_H', '#define HTTP_ALL_SETTINGS_H',
         '#include <stdint.h>', '#include "http_sensor_settings.h"',
         'typedef struct { uint8_t hour, minute, second; } HTTP_SettingsTime;',
         'typedef struct { char name[31]; uint8_t mode; } HTTP_PortSettings;']
    bindings, members = [], []
    for route, name, group in GROUPS:
        page_index, page = by_route[route]
        fields = page["fields"]
        h.append(f'/* {route}: {page["title"]} */\ntypedef struct {{')
        if name in CUSTOM:
            h.append('    ' + CUSTOM[name])
        else:
            names = set()
            for field in fields:
                field_name = member(field)
                assert field_name not in names, (route, field_name)
                names.add(field_name)
                ctype, _ = value_type(field)
                declaration = f'char {field_name}{ctype[4:]}' if ctype.startswith('char[') else f'{ctype} {field_name}'
                h.append(f'    {declaration}; /* {field["name"]} */')
        h.append(f'}} HTTP_{name}Settings;')
        count = page["max_instance"]
        members.append(f'    HTTP_{name}Settings {group}' + (f'[{count}]' if count else '') + ';')
        for index, field in enumerate(fields):
            _, conversion = value_type(field)
            item = target(name, field)
            expression = f'{group}[0].{item}' if count else f'{group}.{item}'
            stride = f'sizeof(HTTP_{name}Settings)' if count else '0'
            bindings.append(f'    {{{page_index}, {index}, {count}, {stride}, offsetof(HTTP_AllSettings, {expression}), sizeof(HTTP_AllSettingsData.{expression}), ALL_{conversion}}},')
    h += ['/* Array indices start at zero. Timer/output instances follow /timNNN and',
          ' * /wypkNNN, not physical GPIO numbers. weekdays[0] is Monday.',
          ' * Decimal fields suffixed _x100 are in hundredths; durations are seconds.',
          ' * IPv4 is 0xC0A80102 for 192.168.1.2. Sensor values retain their original',
          ' * tenths units from HttpSensorSettings. Strings include passwords: do not log.',
          ' * Untouched fields contain the same effective defaults as their forms. */',
          'typedef struct {', '    uint32_t revision;', *members,
          '    HTTP_PortSettings ports[33];',
          '    HttpSensorSettings sensors[HTTP_SENSOR_PORT_COUNT][2]; /* [port-1][0=temp,1=RH] */',
          '} HTTP_AllSettings;',
          '/* Stable global address. Treat as read-only: direct writes do not validate',
          ' * or persist. Updates occur only after successful save/load (or defaults',
          ' * initialization). Use from the HTTP task; other tasks must synchronize',
          ' * with it before reading multiple fields during an update. */',
          'extern HTTP_AllSettings HTTP_AllSettingsData;',
          'const HTTP_AllSettings *HTTP_SettingsGetAll(void);',
          '/* Internal notification from the separate sensor settings store. */',
          'void HTTP_SettingsSensorsUpdate(const HttpSensorSettings *values, size_t count);',
          '#endif', '']
    page_index, page = by_route['/set']
    for index, field in enumerate(page['fields']):
        match = re.fullmatch(r'n_s_Port_nazwa(\d+)_001|n_GPIO_val_(\d+)', field['name'])
        assert match, field['name']
        number = int(match[1] or match[2])-1
        item, conversion = ('name', 'TEXT') if match[1] else ('mode', 'BYTE')
        expression = f'ports[{number}].{item}'
        bindings.append(f'    {{{page_index}, {index}, 0, 0, offsetof(HTTP_AllSettings, {expression}), sizeof(HTTP_AllSettingsData.{expression}), ALL_{conversion}}},')
    inc = ['/* Generated bindings: one entry for every field in the settings catalog. */',
           'static const SettingsAllBinding settingsAllBindings[] = {', *bindings, '};', '']
    assert len(bindings) == sum(len(p['fields']) for p in pages)
    return '\n'.join(h), '\n'.join(inc)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    pages = catalog.build_pages(json.loads(catalog.FIXTURE.read_text())['templates'])
    header, bindings = generate(pages)
    for name, contents in [('http_all_settings.h', header), ('http_all_settings_bindings.inc', bindings)]:
        path = ROOT / 'Application/HTTP' / name
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f'Stale generated settings structure: {path}')
        else:
            path.write_text(contents)
    print('PASS: all catalog fields represented in the global settings structure.')


if __name__ == '__main__':
    main()
