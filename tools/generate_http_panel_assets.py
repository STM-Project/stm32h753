#!/usr/bin/env python3
"""Embed the /main,/set loader and version URLs from every template dependency.
Run after editing panels.js, wwwPages.c or the neutral template renderer.
No SD files, dependencies or CubeMX/project configuration are required.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]

def generate():
    esp = (ROOT / 'Application/esp32wroom.c').read_text()
    start = esp.index('\tcase WWW_PANEL_SET_TEMPLATE:')
    end = esp.index('\tcase WWW_SENSOR_SETTING:', start)
    js = (ROOT / 'Application/HTTP/web/panels.js').read_text()
    dependencies = (ROOT / 'Application/wwwPages.c').read_bytes() + (ROOT / 'Application/wwwPages.h').read_bytes() + esp[start:end].encode() + js.encode()
    version = hashlib.sha256(dependencies).hexdigest()[:16]
    prefix = '/assets/h7-panels-' + version
    script = ('var H7_READ_TEMPLATE=' + json.dumps(prefix + '-read.htm') + ';\n' +
              'var H7_SET_TEMPLATE=' + json.dumps(prefix + '-set.htm') + ';\n' + js)
    return ('/* Generated by tools/generate_http_panel_assets.py; edit web/panels.js. */\n' +
            '#define HTTP_PANEL_SCRIPT_PATH "' + prefix + '.js"\n' +
            '#define HTTP_PANEL_READ_PATH "' + prefix + '-read.htm"\n' +
            '#define HTTP_PANEL_SET_PATH "' + prefix + '-set.htm"\n' +
            'static const char HTTP_PanelScript[] =\n' +
            '\n'.join('\t' + json.dumps(line, ensure_ascii=True) for line in script.splitlines(True)) + ';\n')

if __name__ == '__main__':
    target = ROOT / 'Application/HTTP/http_panel_assets.inc'
    result = generate()
    if '--check' in sys.argv:
        if not target.exists() or target.read_text() != result:
            sys.exit('HTTP panel assets are stale: run python3 tools/generate_http_panel_assets.py')
    else:
        target.write_text(result)
